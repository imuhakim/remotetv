"""Builds public/native/ircodes.js from IRDB (https://github.com/probonopd/irdb).

Usage: python scripts/ircodes.py <folder with the downloaded IRDB csv files>
Each CSV row is: functionname,protocol,device,subdevice,function.
"""
import csv
import json
import os
import re
import sys

SETS = [  # brand key, label, csv file name, protocol name used by the encoder
    ('toshiba', 'Toshiba', 'Toshiba_TV_64_-1.csv', 'nec1'),
    ('sharp', 'Sharp', 'Sharp_TV_1_-1.csv', 'sharp'),
    ('panasonic', 'Panasonic', 'Panasonic_TV_128_0.csv', 'panasonic'),
    ('philips', 'Philips', 'Philips_TV_0_-1.csv', 'rc5'),
    ('tcl', 'TCL', 'TCL_TV_15_-1.csv', 'rca38'),
    ('sanyo', 'Sanyo', 'Sanyo_TV_56_-1.csv', 'nec1'),
    ('hitachi', 'Hitachi', 'Hitachi_TV_80_-1.csv', 'nec1'),
]

# IRDB function name -> RemoteTV key (first matching rule wins per key).
RULES = [
    ('power', r'^(POWER|POWER TOGGLE|TV POWER)$'), ('power_on', r'^POWER ON$'), ('power_off', r'^POWER OFF$'),
    ('mute', r'^(MUTE|VOLUME MUTE TOGGLE|TV MUTE)$'),
    ('vol_up', r'^(VOLUME \+|VOLUME UP|VOL UP|VOLUME \+/CURSOR RT)$'), ('vol_down', r'^(VOLUME -|VOLUME DOWN|VOL DOWN|VOLUME -/CURSOR LT)$'),
    ('ch_up', r'^(CHANNEL \+|CHANNEL UP|CHANNEL \+/CURSOR UP)$'), ('ch_down', r'^(CHANNEL -|CHANNEL DOWN|CHANNEL -/CURSOR DN)$'),
    ('input', r'^(INPUT SOURCE|INPUT|TV/VIDEO|INPUT SELECT/SCROLL|EXT\. INPUT|INPUT NEXT)$'),
    ('menu', r'^(MENU|MENU/ENTER|MENU / ENTER)$'),
    ('up', r'^(CURSOR UP|UP|ARROW UP)$'), ('down', r'^(CURSOR DOWN|DOWN|ARROW DOWN)$'),
    ('left', r'^(CURSOR LEFT|LEFT|ARROW LEFT)$'), ('right', r'^(CURSOR RIGHT|RIGHT|ARROW RIGHT)$'),
    ('ok', r'^(OK|SELECT|CURSOR ENTER/SELECT)$'),  # plain "ENTER" is channel-number entry on these remotes
    ('back', r'^(RETURN|BACK|GO BACK|EXIT)$'),
    ('info', r'^(INFO|DISPLAY|INFO / RECALL|RECALL|STATUS)$'), ('guide', r'^(GUIDE|TV GUIDE)$'),
    ('play_pause', r'^(PLAY PAUSE)$'), ('stop', r'^STOP$'),
    ('red', r'^(RED|COLOR BUTTON RED)$'), ('green', r'^(GREEN|COLOR BUTTON GREEN)$'),
    ('yellow', r'^(YELLOW|COLOR BUTTON YELLOW)$'), ('blue', r'^(BLUE|COLOR BUTTON BLUE)$'),
]
for n in range(10):
    RULES.append((str(n), r'^(DIGIT )?%d%s$' % (n, '(/10)?' if n == 0 else '')))

# TVs whose remote has no separate arrows use CH/VOL as cursor keys in menus.
FALLBACK = {'up': 'ch_up', 'down': 'ch_down', 'left': 'vol_down', 'right': 'vol_up', 'ok': 'menu', 'settings': 'menu'}


def build(folder):
    out = {}
    for key, label, name, proto in SETS:
        rows = list(csv.DictReader(open(os.path.join(folder, name), encoding='utf8')))
        dev, sub = int(rows[0]['device']), int(rows[0]['subdevice'])
        keys = {}
        for k, rx in RULES:
            for r in rows:
                fn = (r['functionname'] or '').strip().upper()
                if r['protocol'].replace('{2}', '') not in ('NEC1', 'Sharp', 'Panasonic', 'RC5', 'RCA-38', 'NECx2'):
                    continue
                if r['protocol'] == 'Sharp{2}':
                    continue
                if re.match(rx, fn) and k not in keys:
                    keys[k] = int(r['function'])
        if '1' not in keys and '2' in keys:  # IRDB lists Sharp's "1" without a name
            keys['1'] = keys['2'] - 1
        for k, src in FALLBACK.items():
            if k not in keys and src in keys:
                keys[k] = keys[src]
        out[key] = {'label': label, 'proto': proto, 'd': dev, 's': sub, 'keys': keys}
    return out


if __name__ == '__main__':
    data = build(sys.argv[1])
    js = ("'use strict';\n/* Generated by scripts/ircodes.py from IRDB (github.com/probonopd/irdb). Do not edit by hand.\n"
          " * Infra-red TV code sets: protocol, device, subdevice and RemoteTV key -> function code. */\n"
          "window.IR_CODES = " + json.dumps(data, indent=1) + ";\n")
    open(os.path.join(os.path.dirname(__file__), '..', 'public', 'native', 'ircodes.js'), 'w', encoding='utf8').write(js)
    for k, v in data.items():
        print(k, v['proto'], v['d'], len(v['keys']), sorted(v['keys']))
