'use strict';
// Copies browser builds of the libraries the in-app (APK) backend needs into
// public/vendor so the app works offline. Run by `npm run build:web`.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'public', 'vendor');
fs.mkdirSync(out, { recursive: true });
const files = {
  'forge.min.js': 'node_modules/node-forge/dist/forge.min.js',
  'protobuf.min.js': 'node_modules/protobufjs/dist/protobuf.min.js',
  'capacitor.js': 'node_modules/@capacitor/core/dist/capacitor.js',
};
for (const [name, src] of Object.entries(files)) {
  fs.copyFileSync(path.join(root, src), path.join(out, name));
  console.log(`vendor/${name}`);
}

// Android TV Remote v2 protocol definitions (from louis49/androidtv-remote, MIT),
// embedded as strings so the app needs no extra fetch.
const protoDir = path.join(root, 'node_modules', 'androidtv-remote', 'src');
const protos = {
  pairing: fs.readFileSync(path.join(protoDir, 'pairing', 'pairingmessage.proto'), 'utf8'),
  remote: fs.readFileSync(path.join(protoDir, 'remote', 'remotemessage.proto'), 'utf8'),
};
fs.writeFileSync(path.join(out, 'protos.js'),
  `// Generated by scripts/vendor.js from androidtv-remote (MIT). Do not edit.\nwindow.TV_PROTOS = ${JSON.stringify(protos)};\n`);
console.log('vendor/protos.js');

